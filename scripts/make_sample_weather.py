#!/usr/bin/env python3
"""Writes data/weather/sample_hourly_45n.csv, a synthetic hourly weather file (WP25).

The file exists to exercise the hourly weather reader end to end (M2 exit: "weather
file import drives a run"). It is not observed weather. Each day draws a clearness
index and a rain event from a fixed-seed generator. Temperature follows a seasonal
mean and a diurnal sine; humidity falls as temperature rises. Hourly radiation is the
clearness times the extraterrestrial irradiance at 45 N, at mid-hour, local mean solar
time.

Usage: python3 scripts/make_sample_weather.py
"""

import math
import random
from datetime import date, timedelta
from pathlib import Path

LAT = math.radians(45.0)
START = date(2026, 5, 10)
DAYS = 130
SOLAR = 1361.0


def declination(doy: int) -> float:
    return math.radians(23.44) * math.sin(2 * math.pi * (284 + doy) / 365)


def main() -> None:
    rng = random.Random(25)
    out = Path(__file__).resolve().parent.parent / "data" / "weather" / "sample_hourly_45n.csv"
    lines = [
        "# Synthetic hourly weather at 45 N, 10 May to 16 Sep 2026, local mean solar time.",
        "# Generated by scripts/make_sample_weather.py (fixed seed); not observed weather.",
        "timestamp,t_air_c,rh_pct,radiation_w_m2,rain_mm,wind_m_s",
    ]
    for d in range(DAYS):
        day = START + timedelta(days=d)
        doy = day.timetuple().tm_yday
        dec = declination(doy)
        # Seasonal mean: about 20 C from late May to July, falling to 16 C by mid September.
        season = 18.5 + 4.0 * math.sin(2 * math.pi * (doy - 120) / 365 * 1.6)
        kt = min(0.75, max(0.25, rng.gauss(0.58, 0.13)))
        amplitude = 4.0 + 8.0 * (kt - 0.25) / 0.5
        rain_day = rng.random() < 0.25
        rain_total = rng.expovariate(1 / 8.0) if rain_day else 0.0
        rain_start = rng.randrange(10, 22)
        rain_hours = rng.randrange(1, 5)
        for h in range(24):
            omega = math.radians(15.0 * (h + 0.5 - 12.0))
            sin_el = math.sin(LAT) * math.sin(dec) + math.cos(LAT) * math.cos(dec) * math.cos(omega)
            g = max(0.0, SOLAR * kt * sin_el)
            t = season + 0.5 * amplitude * math.sin(2 * math.pi * (h - 9.0) / 24)
            rh = min(98.0, max(30.0, 75.0 - 3.0 * (t - season) + (10.0 if rain_day else 0.0)))
            rain = rain_total / rain_hours if rain_start <= h < rain_start + rain_hours else 0.0
            wind = 1.5 + 1.0 * max(0.0, math.sin(2 * math.pi * (h - 8.0) / 24))
            lines.append(
                f"{day.isoformat()}T{h:02d}:00,{t:.2f},{rh:.1f},{g:.1f},{rain:.2f},{wind:.2f}"
            )
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({DAYS * 24} hours)")


if __name__ == "__main__":
    main()
