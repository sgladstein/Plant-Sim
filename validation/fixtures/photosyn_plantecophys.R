# Gas-exchange fixture from plantecophys::Photosyn (design plan §8.1, WP7).
# Usage: Rscript validation/fixtures/photosyn_plantecophys.R [out.csv]
# Requires: install.packages("plantecophys")  (tested with 1.4-6)
# The grid and parameters mirror validation/fixtures/photosyn_grid.py.
suppressPackageStartupMessages(library(plantecophys))
args <- commandArgs(trailingOnly = TRUE)
out <- if (length(args) > 0) args[1] else "crates/ps-physio/tests/fixtures/photosyn.csv"

g <- expand.grid(par = c(50, 100, 200, 400, 800, 1200, 1600, 2000),
                 tleaf = c(10, 15, 20, 25, 30, 35, 40),
                 vpd = c(0.5, 1.0, 1.5, 2.0, 3.0, 4.0),
                 ca = c(280, 420, 800))
g <- g[order(g$par, g$tleaf, g$vpd, g$ca), ]
r <- Photosyn(PPFD = g$par, Tleaf = g$tleaf, VPD = g$vpd, Ca = g$ca, Patm = 100,
              gsmodel = "BBOpti", g1 = 4.0, g0 = 0.01, alpha = 0.3, theta = 0.7,
              Vcmax = 89.3, Jmax = 159.8, Rd0 = 0.88, Q10 = 1.92, TrefR = 25,
              EaV = 58550, EdVC = 200000, delsC = 629.26,
              EaJ = 29680, EdVJ = 200000, delsJ = 631.88)
df <- data.frame(par = g$par, tleaf = g$tleaf, vpd = g$vpd, ca = g$ca,
                 a_net = r$ALEAF, gs = r$GS, e = r$ELEAF / 1000, ci = r$Ci)
con <- file(out, "w")
writeLines(sprintf("# generated by validation/fixtures/photosyn_plantecophys.R, plantecophys %s",
                   packageVersion("plantecophys")), con)
write.csv(df, con, row.names = FALSE, quote = FALSE)
close(con)
