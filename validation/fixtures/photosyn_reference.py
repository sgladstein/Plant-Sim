#!/usr/bin/env python3
"""Gas-exchange fixture without R: an independent implementation of the equations
plantecophys::Photosyn (version 1.4-6, Duursma 2015) uses with gsmodel = "BBOpti".

The reference is plantecophys itself (photosyn_plantecophys.R). This script exists
because the build environment cannot reach CRAN; CI runs the R script and checks that
both agree (compare_photosyn.py). Equations (Duursma 2015, Medlyn et al. 2011,
Bernacchi et al. 2001, Medlyn et al. 2002):

  Kc = 404.9 exp(79430 (Tk - 298.15) / (298.15 R Tk))       umol mol-1
  Ko = 278.4 exp(36380 (Tk - 298.15) / (298.15 R Tk))       mmol mol-1
  Km = Kc (1 + Oi / Ko), Oi = 210 Patm / 100
  Gamma* = 42.75 exp(37830 (Tk - 298.15) / (298.15 R Tk)) Patm / 100
  peaked Arrhenius for Vcmax and Jmax; Rd = Rd0 Q10^((T - TrefR) / 10)
  J = non-rectangular hyperbola of absorbed PAR (alpha, theta, Jmax)
  gs/A (CO2) = (1 + g1 / sqrt(max(VPD, 0.5))) / Ca; GS(H2O) = 1.57 GS(CO2)
  Ci from the quadratic intersection of supply and demand per limitation,
  A = hyperbolic minimum (0.9999) of Ac and Aj, minus Rd; E = GS VPD / Patm.

What it mirrors from plantecophys 1.4-6 Photosyn(), and how sure that is:
  - Read from plantecophys R/photosyn.R (GitHub mirror): the BBOpti conductance form
    (vpdmin 0.5, gk 0.5, g0 converted to CO2 by 1/1.57, GS clamped at g0), the two
    MAESTRA quadratics for Ci, the low-light rule (Aj <= Rd + 1e-9 sets Ci = Ca), the
    hyperbolic minimum with 1 - 1e-4, Rd = Rd0 Q10^((T - TrefR)/10) with Rdayfrac 1,
    J from the non-rectangular hyperbola, E = 1000 GS VPD / Patm mmol.
  - Not readable here (the helper file was out of reach), written from the published
    sources plantecophys cites: TVcmax/TJmax peaked Arrhenius (Medlyn 2002 eq. 18,
    reference 25 C), TKm and TGammaStar from Bernacchi 2001 (Kc25 404.9, Ec 79430,
    Ko25 278.4, Eo 36380, O 210 mmol/mol, Gamma*25 42.75, Eg 37830), R 8.314 J/mol/K,
    Tk = T + 273.15. The grid uses Patm = 100 kPa, so any pressure scaling is moot.
  The CI job "plantecophys" (linux.yml) reruns the grid in R and fails on any
  difference above 1e-6 relative, which is what proves these.

Usage: python validation/fixtures/photosyn_reference.py [out.csv]
"""

from __future__ import annotations

import math
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from photosyn_grid import CA, COLUMNS, PAR, PARAMS, TLEAF, VPD  # noqa: E402

R = 8.314
GC_TO_GW = 1.57
ROOT = pathlib.Path(__file__).resolve().parents[2]


def quadp(a, b, c):
    d = b * b - 4 * a * c
    if d < 0:
        return 0.0
    if a == 0:
        return 0.0 if b == 0 else -c / b
    return (-b + math.sqrt(d)) / (2 * a)


def arrh(t, ea):
    tk = t + 273.15
    return math.exp(ea * (tk - 298.15) / (298.15 * R * tk))


def peaked(t, ea, ds, ed):
    tk = t + 273.15
    v1 = 1 + math.exp((ds * 298.15 - ed) / (R * 298.15))
    v2 = 1 + math.exp((ds * tk - ed) / (R * tk))
    return math.exp((t - 25) * ea / (R * tk * 298.15)) * v1 / v2


def photosyn(par, t, vpd, ca, p=PARAMS):
    patm = p["Patm"]
    g0 = p["g0"] / GC_TO_GW
    rd = p["Rd0"] * p["Q10"] ** ((t - p["TrefR"]) / 10)
    gstar = 42.75 * arrh(t, 37830.0) * patm / 100
    oi = 210 * patm / 100
    km = 404.9 * arrh(t, 79430.0) * (1 + oi / (278.4 * arrh(t, 36380.0)))
    vcmax = p["Vcmax"] * peaked(t, p["EaV"], p["delsC"], p["EdVC"])
    jmax = p["Jmax"] * peaked(t, p["EaJ"], p["delsJ"], p["EdVJ"])
    a_, th = p["alpha"], p["theta"]
    j = (a_ * par + jmax - math.sqrt((a_ * par + jmax) ** 2 - 4 * a_ * th * par * jmax)) / (2 * th)
    vj = j / 4
    gsdiva = (1 + p["g1"] / math.sqrt(max(vpd, 0.5))) / ca

    a = g0 + gsdiva * (vcmax - rd)
    b = (1 - ca * gsdiva) * (vcmax - rd) + g0 * (km - ca) - gsdiva * (vcmax * gstar + km * rd)
    c = -(1 - ca * gsdiva) * (vcmax * gstar + km * rd) - g0 * km * ca
    cic = quadp(a, b, c)
    a = g0 + gsdiva * (vj - rd)
    b = (1 - ca * gsdiva) * (vj - rd) + g0 * (2 * gstar - ca) - gsdiva * (vj * gstar + 2 * gstar * rd)
    c = -(1 - ca * gsdiva) * gstar * (vj + 2 * rd) - g0 * 2 * gstar * ca
    cij = quadp(a, b, c)

    ac = vcmax * (cic - gstar) / (cic + km)
    aj = vj * (cij - gstar) / (cij + 2 * gstar)
    if aj <= rd + 1e-9:
        cij = ca
        aj = vj * (cij - gstar) / (cij + 2 * gstar)
    ci = cij if aj < ac else cic
    am = -quadp(1 - 1e-4, ac + aj, ac * aj)
    am -= rd
    gs = max(g0 + gsdiva * am, g0) * GC_TO_GW
    e = gs * vpd / patm
    return am, gs, e, ci


def main() -> None:
    out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "crates/ps-physio/tests/fixtures/photosyn.csv"
    with open(out, "w", encoding="utf-8") as f:
        f.write("# generated by validation/fixtures/photosyn_reference.py (plantecophys 1.4-6 equations; "
                "R unavailable, checked against plantecophys in CI)\n")
        f.write(",".join(COLUMNS) + "\n")
        for par in PAR:
            for t in TLEAF:
                for vpd in VPD:
                    for ca in CA:
                        am, gs, e, ci = photosyn(par, t, vpd, ca)
                        f.write(f"{par},{t},{vpd},{ca},{am:.10g},{gs:.10g},{e:.10g},{ci:.10g}\n")


if __name__ == "__main__":
    main()
