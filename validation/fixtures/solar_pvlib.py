#!/usr/bin/env python3
"""Generate the WP2 solar reference fixture with pvlib's NREL SPA.

The sim clock is local mean solar time (docs/decisions/0005), which equals UTC at
longitude 0, so positions are computed at longitude 0 in UTC.

Output: crates/ps-weather/tests/fixtures/solar_pvlib.csv with one row per
(latitude, date, hour midpoint): true elevation (no refraction) and azimuth, plus
sunrise/sunset/day length rows.

Requires: pvlib (tested with 0.16.1), pandas.
Run: python validation/fixtures/solar_pvlib.py
"""

from __future__ import annotations

import pathlib

import pandas as pd
import pvlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "ps-weather" / "tests" / "fixtures"

LATITUDES = [0.0, 45.0, 60.0]
DATES = [
    "2000-01-15", "2000-02-29", "2000-03-20", "2000-04-30", "2000-05-15",
    "2000-06-21", "2000-08-01", "2000-09-22", "2000-11-05", "2000-12-21",
]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    pos_rows = []
    day_rows = []
    for lat in LATITUDES:
        for date in DATES:
            times = pd.date_range(f"{date} 00:30", periods=24, freq="h", tz="UTC")
            sp = pvlib.solarposition.spa_python(times, lat, 0.0, altitude=0, pressure=101325, temperature=12)
            for t, row in sp.iterrows():
                pos_rows.append(
                    dict(latitude=lat, date=date, hour=t.hour + 0.5,
                         elevation=row["elevation"], azimuth=row["azimuth"])
                )
            day = pd.DatetimeIndex([pd.Timestamp(f"{date} 12:00", tz="UTC")])
            rst = pvlib.solarposition.sun_rise_set_transit_spa(day, lat, 0.0)
            sr, ss = rst["sunrise"].iloc[0], rst["sunset"].iloc[0]
            if pd.isna(sr) or pd.isna(ss):
                continue
            base = pd.Timestamp(f"{date} 00:00", tz="UTC")
            day_rows.append(
                dict(latitude=lat, date=date,
                     sunrise_h=(sr - base).total_seconds() / 3600,
                     sunset_h=(ss - base).total_seconds() / 3600)
            )
    header = f"# generated by validation/fixtures/solar_pvlib.py with pvlib {pvlib.__version__} (NREL SPA)\n"
    with open(OUT / "solar_pvlib.csv", "w", encoding="utf-8") as f:
        f.write(header)
        pd.DataFrame(pos_rows).to_csv(f, index=False, float_format="%.6f")
    with open(OUT / "daylight_pvlib.csv", "w", encoding="utf-8") as f:
        f.write(header)
        pd.DataFrame(day_rows).to_csv(f, index=False, float_format="%.6f")


if __name__ == "__main__":
    main()
